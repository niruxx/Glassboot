constexpr uint64_t kMiB = 1 << 20;

uint32_t random32() {
    std::random_device rd;
    return (uint32_t(rd()) << 16) ^ uint32_t(rd());
}

std::string hex32(uint32_t v) {
    char b[16];
    std::snprintf(b, sizeof b, "%08X", v);
    return b;
}

// GRUB environment block: exactly 1024 bytes, '#'-padded. GRUB's save_env rewrites it in
// place to record which ISO was chosen (used by the Windows PE helper).
std::vector<uint8_t> grubEnvBlock() {
    std::string s = "# GRUB Environment Block\n"
                    "# WARNING: Do not edit this file by tools other than grub-editenv!!!\n";
    s.resize(1024, '#');
    return {s.begin(), s.end()};
}

std::vector<uint8_t> readmeText(const Payload& p) {
    std::string s =
        "Glassboot " + p.version + " data partition.\r\n"
        "\r\n"
        "Copy .iso files anywhere on this drive (any folder), then boot from the USB\r\n"
        "stick and pick one from the menu.\r\n"
        "\r\n"
        "Do not delete this \"glassboot\" folder: it is used when booting Windows ISOs.\r\n";
    return {s.begin(), s.end()};
}

// Progress bookkeeping shared by install() and update(): weighted steps.
class Steps {
public:
    Steps(const InstallCallbacks& cb, const std::atomic<bool>& cancel) : cb_(cb), cancel_(cancel) {}
    void log(const std::string& s) const { if (cb_.log) cb_.log(s); }
    void step(double w, const std::string& name) {
        checkCancel();
        base_ += weight_;
        weight_ = w;
        name_ = name;
        log("==> " + name);
        if (cb_.progress) cb_.progress(base_, name);
    }
    void sub(double f) const { if (cb_.progress) cb_.progress(base_ + weight_ * f, name_); }
    void done() const { if (cb_.progress) cb_.progress(1.0, "Done"); }
    void checkCancel() const { if (cancel_) throw Error("cancelled"); }

private:
    const InstallCallbacks& cb_;
    const std::atomic<bool>& cancel_;
    double base_ = 0, weight_ = 0;
    std::string name_;
};

// Write esp.img at `espStart`, personalising hidden-sectors and the volume serial.
void writeEsp(BlockDevice& dev, const Payload& payload, uint64_t espStart, uint32_t serial, Steps& s) {
    std::ifstream f(dev.logicalSectorSize() == 4096 ? payload.esp4kImagePath : payload.espImagePath, std::ios::binary);
    if (!f) throw Error("cannot open " + payload.espImagePath);
    const size_t chunk = 4 * kMiB;
    AlignedBuffer buf(chunk);
    const uint64_t espOffset = uint64_t(espStart) * 512;
    for (uint64_t done = 0; done < payload.espImageSize;) {
        size_t n = size_t(std::min<uint64_t>(chunk, payload.espImageSize - done));
        f.read(reinterpret_cast<char*>(buf.data()), std::streamsize(n));
        if (size_t(f.gcount()) != n) throw Error("short read from esp.img");
        if (done == 0) {
            if (std::memcmp(buf.data() + 0x36, "FAT16   ", 8) != 0) throw Error("esp.img is not FAT16");
            uint8_t* b = buf.data();
            uint64_t hidden = espStart / (dev.logicalSectorSize() / 512);
            if (uint32_t(b[11] | uint32_t(b[12]) << 8) != dev.logicalSectorSize()) throw Error("ESP sector size does not match the device");
            for (int i = 0; i < 4; ++i) b[0x1C + i] = hidden > 0xFFFFFFFFull ? 0 : uint8_t(hidden >> (8 * i));
            for (int i = 0; i < 4; ++i) b[0x27 + i] = uint8_t(serial >> (8 * i));   // volume serial
        }
        dev.write(espOffset + done, buf.data(), n);
        done += n;
        s.sub(double(done) / double(payload.espImageSize));
        s.checkCancel();
    }
}

void writeSector(BlockDevice& dev, uint64_t lba, const uint8_t* data) {
    AlignedBuffer b(512);
    std::memcpy(b.data(), data, 512);
    dev.write(lba * 512, b.data(), 512);
}

void writeCore(BlockDevice& dev, const std::vector<uint8_t>& core) {
    AlignedBuffer b(core.size());
    std::memcpy(b.data(), core.data(), core.size());
    dev.write(512, b.data(), b.size());
}

// Read back MBR, core.img, marker and the ESP and compare with what was written.
void verify(BlockDevice& dev, const Payload& payload, const std::array<uint8_t, 512>& mbr,
            const std::vector<uint8_t>& core, const std::array<uint8_t, 512>& marker, uint64_t espStart, Steps& s) {
    {
        AlignedBuffer b(core.size() + 512);
        dev.read(0, b.data(), b.size());
        if (std::memcmp(b.data(), mbr.data(), 512) != 0) throw Error("verification failed: MBR");
        if (!core.empty() && std::memcmp(b.data() + 512, core.data(), core.size()) != 0) throw Error("verification failed: core.img");
        AlignedBuffer m(512);
        dev.read(kMarkerLba * 512, m.data(), 512);
        if (std::memcmp(m.data(), marker.data(), 512) != 0) throw Error("verification failed: marker");
    }
    std::ifstream f(dev.logicalSectorSize() == 4096 ? payload.esp4kImagePath : payload.espImagePath, std::ios::binary);
    const size_t chunk = 4 * kMiB;
    AlignedBuffer disk(chunk);
    std::vector<char> want(chunk);
    const uint64_t espOffset = uint64_t(espStart) * 512;
    for (uint64_t done = 0; done < payload.espImageSize;) {
        size_t n = size_t(std::min<uint64_t>(chunk, payload.espImageSize - done));
        f.read(want.data(), std::streamsize(n));
        dev.read(espOffset + done, disk.data(), n);
        if (done == 0) { // personalised fields
            std::memcpy(want.data() + 0x1C, disk.data() + 0x1C, 4);
            std::memcpy(want.data() + 0x27, disk.data() + 0x27, 4);
        }
        if (std::memcmp(disk.data(), want.data(), n) != 0)
            throw Error("verification failed: EFI partition differs at offset " + std::to_string(done) +
                        ". The USB drive may be faulty or counterfeit.");
        done += n;
        s.sub(double(done) / double(payload.espImageSize));
        s.checkCancel();
    }
}

